// loadConway loads a conway polynomial of degree N.
func loadConaway(N int) z2xPoly {
	if N <= 0 || N >= len(conwayPolynomial) {
		panic("invalid conway polynomial degree")
	}

	cp := make(z2xPoly, N+1)
	lo, hi := conwayPolynomial[N][0], conwayPolynomial[N][1]
	if N < 64 {
		for i := 0; i <= N; i++ {
			cp[i] = (lo >> i) & 1
		}
	} else {
		for i := 0; i < 64; i++ {
			cp[i] = (lo >> i) & 1
		}
		for i := 0; i <= N-64; i++ {
			cp[i+64] = (hi >> i) & 1
		}
	}

	return cp
}
